#!/usr/bin/env python3
"""Generate the Lennard-Jones (energy-only) benchmark programs for the Kites LNS extension.

Writes, next to this script (or into --out):
  lj_fp32.s        FP32 control: flw / fsub.s / fmul.s / fadd.s / fdiv.s
  lj_lns.s         LNS with the table-based add/sub (ladd / lsub)
  lj_lns_cordic.s  identical to lj_lns.s except ladd -> laddc, lsub -> lsubc
  reference.txt    FP64 energy computed from the float32-rounded positions

Atoms sit on a simple-cubic lattice (spacing 1.12, sigma = eps = 1) with fixed deterministic
offsets in [-0.05, +0.05], rounded to float32. Pair kernel for i < j, same op order everywhere:
  dx = xi - xj, dy, dz;  r2 = (dx*dx + dy*dy) + dz*dz;  inv = 1 / r2
  s6 = (inv*inv)*inv;  s12 = s6*s6;  v = 4*(s12 - s6);  E += v
E is reset at the start of every repeat, so the final register holds the energy of one pass.
Final energy: FP32 -> f10; LNS -> l10 (la0), then fcvt.s.lns into f11. Exit with a7 = 10.

Plain Python, float64 only (no numpy).
"""

import argparse
import math
import os
import struct

SPACING = 1.12
ORIGIN = 1.0  # keeps every coordinate positive
MAX_OFFSET = 0.05


def f32(x):
    """Round a float64 to the nearest float32 and return it as a float64."""
    return struct.unpack("<f", struct.pack("<f", x))[0]


def f32_literal(x):
    """Shortest decimal that std::stof reads back as exactly the float32 value x."""
    for digits in range(6, 10):
        s = "%.*g" % (digits, x)
        if f32(float(s)) == x:
            break
    if "e" in s or "E" in s:
        raise ValueError("unexpected exponent in literal: " + s)
    if "." not in s:
        s += ".0"
    return s


def positions(n_side):
    """Lattice positions with deterministic offsets (a small LCG), rounded to float32."""
    state = 12345
    pos = []
    for ix in range(n_side):
        for iy in range(n_side):
            for iz in range(n_side):
                atom = []
                for base in (ix, iy, iz):
                    state = (1103515245 * state + 12345) % (1 << 31)
                    offset = ((state >> 8) % 2001 - 1000) / 1000.0 * MAX_OFFSET
                    atom.append(f32(ORIGIN + base * SPACING + offset))
                pos.append(tuple(atom))
    return pos


def reference_energy(pos):
    energy = 0.0
    for i in range(len(pos)):
        for j in range(i + 1, len(pos)):
            dx = pos[i][0] - pos[j][0]
            dy = pos[i][1] - pos[j][1]
            dz = pos[i][2] - pos[j][2]
            r2 = (dx * dx + dy * dy) + dz * dz
            inv = 1.0 / r2
            s6 = (inv * inv) * inv
            s12 = s6 * s6
            energy += 4.0 * (s12 - s6)
    return energy


def data_section(pos, with_lns_buffer):
    lines = [".data"]
    floats = [f32_literal(c) for atom in pos for c in atom]
    lines.append("pos: .float " + ", ".join(floats[:3]))
    for k in range(3, len(floats), 3):
        lines.append("     .float " + ", ".join(floats[k:k + 3]))
    if with_lns_buffer:
        lines.append("lone: .word 0          # LNS +1.0 (raw word 0x00000000)")
        lines.append("lbuf: .zero %d" % (12 * len(pos)))
    return lines


EXIT = [
    "    li a0, 0",
    "    li a7, 10                  # exit",
    "    ecall",
]


def fp32_program(pos, repeats):
    n = len(pos)
    lines = ["# Lennard-Jones pair energy, FP32 control (generated by gen_lj.py: N=%d, REPEATS=%d)"
             % (n, repeats), "# Final energy (one pass) in f10."]
    lines += data_section(pos, False)
    lines += [
        ".text",
        "    la s0, pos",
        "    li s1, %d                  # N" % n,
        "    li s2, %d                  # REPEATS" % repeats,
        "    li t0, 0x3F800000",
        "    fmv.w.x f21, t0            # 1.0",
        "    li t0, 0x40800000",
        "    fmv.w.x f20, t0            # 4.0",
        "rep_loop:",
        "    fmv.w.x f10, zero          # E = 0",
        "    li t1, 0                   # i",
        "    mv t3, s0                  # &pos[i]",
        "i_loop:",
        "    flw f0, 0(t3)",
        "    flw f1, 4(t3)",
        "    flw f2, 8(t3)",
        "    addi t2, t1, 1             # j = i + 1",
        "    addi t4, t3, 12            # &pos[j]",
        "    bge t2, s1, i_next",
        "j_loop:",
        "    flw f3, 0(t4)",
        "    flw f4, 4(t4)",
        "    flw f5, 8(t4)",
        "    fsub.s f3, f0, f3          # dx",
        "    fsub.s f4, f1, f4          # dy",
        "    fsub.s f5, f2, f5          # dz",
        "    fmul.s f6, f3, f3",
        "    fmul.s f7, f4, f4",
        "    fadd.s f6, f6, f7",
        "    fmul.s f7, f5, f5",
        "    fadd.s f6, f6, f7          # r2",
        "    fdiv.s f7, f21, f6         # inv = 1 / r2",
        "    fmul.s f8, f7, f7",
        "    fmul.s f8, f8, f7          # s6",
        "    fmul.s f9, f8, f8          # s12",
        "    fsub.s f9, f9, f8          # s12 - s6",
        "    fmul.s f9, f20, f9         # v = 4 * (s12 - s6)",
        "    fadd.s f10, f10, f9        # E += v",
        "    addi t2, t2, 1",
        "    addi t4, t4, 12",
        "    blt t2, s1, j_loop",
        "i_next:",
        "    addi t1, t1, 1",
        "    addi t3, t3, 12",
        "    blt t1, s1, i_loop",
        "    addi s2, s2, -1",
        "    bnez s2, rep_loop",
    ] + EXIT
    return lines


def lns_program(pos, repeats, add, sub, label):
    n = len(pos)
    lines = ["# Lennard-Jones pair energy, LNS %s (generated by gen_lj.py: N=%d, REPEATS=%d)"
             % (label, n, repeats),
             "# Final energy (one pass) in l10 (la0) and, converted, in f11.",
             "# L registers: ls0 = 1.0, ls1 = 4.0, ls2-ls4 = xi yi zi, lt0-lt2 = xj yj zj,",
             "#              lt3-lt6 = temporaries, la0 = E."]
    lines += data_section(pos, True)
    lines += [
        ".text",
        "    la s0, pos",
        "    la s3, lbuf",
        "    li s1, %d                  # N" % n,
        "    li s2, %d                  # REPEATS" % repeats,
        "# convert every coordinate once: lbuf[k] = fcvt.lns.s(pos[k])",
        "    li t0, %d                  # 3N words" % (3 * n),
        "    mv t3, s0",
        "    mv t4, s3",
        "cvt_loop:",
        "    flw f0, 0(t3)",
        "    fcvt.lns.s lt0, f0",
        "    lsw lt0, 0(t4)",
        "    addi t3, t3, 4",
        "    addi t4, t4, 4",
        "    addi t0, t0, -1",
        "    bnez t0, cvt_loop",
        "    la t0, lone",
        "    llw ls0, 0(t0)             # 1.0",
        "    li t0, 0x40800000",
        "    fmv.w.x f0, t0",
        "    fcvt.lns.s ls1, f0         # 4.0",
        "rep_loop:",
        "    %s la0, lzero, lzero     # E = 0" % add.ljust(5),
        "    li t1, 0                   # i",
        "    mv t3, s3                  # &lbuf[i]",
        "i_loop:",
        "    llw ls2, 0(t3)",
        "    llw ls3, 4(t3)",
        "    llw ls4, 8(t3)",
        "    addi t2, t1, 1             # j = i + 1",
        "    addi t4, t3, 12            # &lbuf[j]",
        "    bge t2, s1, i_next",
        "j_loop:",
        "    llw lt0, 0(t4)",
        "    llw lt1, 4(t4)",
        "    llw lt2, 8(t4)",
        "    %s lt0, ls2, lt0         # dx" % sub.ljust(5),
        "    %s lt1, ls3, lt1         # dy" % sub.ljust(5),
        "    %s lt2, ls4, lt2         # dz" % sub.ljust(5),
        "    lmul  lt3, lt0, lt0",
        "    lmul  lt4, lt1, lt1",
        "    %s lt3, lt3, lt4" % add.ljust(5),
        "    lmul  lt4, lt2, lt2",
        "    %s lt3, lt3, lt4         # r2" % add.ljust(5),
        "    ldiv  lt4, ls0, lt3         # inv = 1 / r2",
        "    lmul  lt5, lt4, lt4",
        "    lmul  lt5, lt5, lt4         # s6",
        "    lmul  lt6, lt5, lt5         # s12",
        "    %s lt6, lt6, lt5         # s12 - s6" % sub.ljust(5),
        "    lmul  lt6, ls1, lt6         # v = 4 * (s12 - s6)",
        "    %s la0, la0, lt6         # E += v" % add.ljust(5),
        "    addi t2, t2, 1",
        "    addi t4, t4, 12",
        "    blt t2, s1, j_loop",
        "i_next:",
        "    addi t1, t1, 1",
        "    addi t3, t3, 12",
        "    blt t1, s1, i_loop",
        "    addi s2, s2, -1",
        "    bnez s2, rep_loop",
        "    fcvt.s.lns f11, la0",
    ] + EXIT
    return lines


def main():
    here = os.path.dirname(os.path.abspath(__file__))
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--n", type=int, default=27, help="number of atoms, a perfect cube (default 27)")
    # Kites (Release, WSL) runs ~13k instructions/s, so 4 passes take ~2.3 s for FP32.
    ap.add_argument("--repeats", type=int, default=4, help="passes over all pairs (default 4)")
    ap.add_argument("--out", default=here, help="output directory (default: next to this script)")
    args = ap.parse_args()

    n_side = round(args.n ** (1.0 / 3.0))
    if n_side ** 3 != args.n or args.n < 2:
        ap.error("--n must be a perfect cube >= 8")
    if args.repeats < 1:
        ap.error("--repeats must be >= 1")

    pos = positions(n_side)
    energy = reference_energy(pos)
    os.makedirs(args.out, exist_ok=True)

    def write(name, lines):
        with open(os.path.join(args.out, name), "w", newline="\n") as f:
            f.write("\n".join(lines) + "\n")

    write("lj_fp32.s", fp32_program(pos, args.repeats))
    write("lj_lns.s", lns_program(pos, args.repeats, "ladd", "lsub", "table add/sub"))
    write("lj_lns_cordic.s", lns_program(pos, args.repeats, "laddc", "lsubc", "CORDIC add/sub"))
    write("reference.txt", [
        repr(energy),
        "# FP64 Lennard-Jones energy (one pass) from the float32-rounded positions",
        "# N=%d REPEATS=%d spacing=%r max_offset=%r" % (args.n, args.repeats, SPACING, MAX_OFFSET),
    ])
    print("N=%d REPEATS=%d E_ref=%r -> %s" % (args.n, args.repeats, energy, args.out))


if __name__ == "__main__":
    main()
